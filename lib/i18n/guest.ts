export const GUEST_COPY: Record<Locale, GuestCopy> = { en, es };

/**
 * A refusal from the server in the guest's language: its code's line when
 * there is one, else the server's own (English) words, else the fallback.
 */
export function refusalText(t: GuestCopy, body: { code?: unknown; error?: unknown } | null | undefined, fallback: string): string {
  const code = typeof body?.code === "string" ? body.code : null;
  if (code && Object.hasOwn(t.errors, code)) return t.errors[code as keyof GuestCopy["errors"]];
  return typeof body?.error === "string" && body.error ? body.error : fallback;
}

/** An upload's refusal in the guest's language, or its English when no code matches. */
export function uploadRefusalText(
  t: GuestCopy,
  item: { code: string | null; values: Record<string, number | string> | null; message: string | null },
): string {
  if (item.code && Object.hasOwn(t.uploads.refusals, item.code)) {
    return t.uploads.refusals[item.code as keyof GuestCopy["uploads"]["refusals"]](item.values);
  }
  return item.message ?? t.uploads.notAdded;
}
