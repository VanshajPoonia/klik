/** What a set of uploads is, for the words about it. */
export type UploadKind = "photo" | "video" | "mixed";
type Values = Record<string, number | string> | null | undefined;

/** A refusal line: some use the numbers the server sent, most do not. */
type RefusalLine = (values: Values) => string;
const refusalLines = <T extends Record<string, RefusalLine>>(lines: T): { [K in keyof T]: RefusalLine } => lines;

const clock = (seconds: number) => `${Math.floor(seconds / 60)}:${String(Math.round(seconds) % 60).padStart(2, "0")}`;
const num = (values: Values, key: string) => Number(values?.[key] ?? 0);

const enNoun = (n: number, kind: UploadKind) =>
  kind === "photo" ? (n === 1 ? "photo" : "photos") : kind === "video" ? (n === 1 ? "video" : "videos") : "photos and videos";
const esNoun = (n: number, kind: UploadKind) =>
  kind === "photo" ? (n === 1 ? "foto" : "fotos") : kind === "video" ? (n === 1 ? "video" : "videos") : "fotos y videos";
// "Foto" is feminine, "video" masculine, and a mix takes the masculine plural.
const esSaved = (n: number, kind: UploadKind) =>
  kind === "photo" ? (n === 1 ? "guardada" : "guardadas") : n === 1 ? "guardado" : "guardados";

